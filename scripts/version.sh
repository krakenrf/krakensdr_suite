# scripts/version.sh - the suite's version from git, for the builds that
# can't ask git at run time (docs/dev/version.md). Prints key=value lines:
#
#   count=294                       commits on HEAD (not on a shallow clone)
#   hash=63a4917                    abbreviated commit hash
#   date=2026-11-16T00:23:16+13:00  commit date
#   branch=main                     (absent on a detached HEAD)
#   modified=0                      1 = tracked files differ from the commit
#   shallow=0
#
# Nothing (and exit 0) outside a git work tree of the suite or without git.
# The programs format the text ("r294 · 63a4917") from these fields, and ask
# git the same questions themselves when they run in a work tree
# (version_info.cpp in both apps - keep the two alike).
#
#   scripts/version.sh [-C dir] [--ignore-missing]        print
#   scripts/version.sh [-C dir] --header FILE             C header for the Makefiles:
#       #define KRAKEN_BUILD_VERSION "count=...\n..." - FILE is rewritten only
#       when it changes, so make recompiles only what includes it
#
#   -C dir            the work tree (default: the one this script is in)
#   --ignore-missing  files missing from the work tree don't count as
#                     modified (the Docker build context holds only part of it)
set -u

dir=
header=
ignore_missing=0
while [ $# -gt 0 ]; do
    case $1 in
        -C) dir=$2; shift 2 ;;
        --header) header=$2; shift 2 ;;
        --ignore-missing) ignore_missing=1; shift ;;
        *) echo "usage: $0 [-C dir] [--ignore-missing] [--header FILE]" >&2; exit 2 ;;
    esac
done
[ -n "$dir" ] || dir=$(cd "$(dirname "$0")/.." && pwd)

g() { git -C "$dir" "$@" 2>/dev/null; }

info() {
    command -v git >/dev/null 2>&1 || return 0
    top=$(g rev-parse --show-toplevel) || return 0
    # only this suite's work tree (the programs check the same)
    [ -d "$top/heimdall_v2" ] && [ -d "$top/kraken_doa_v2" ] || return 0
    hash=$(g log -1 --abbrev=7 --format=%h HEAD) || return 0
    [ -n "$hash" ] || return 0
    date=$(g log -1 --format=%cI HEAD)
    shallow=0
    [ "$(g rev-parse --is-shallow-repository)" = true ] && shallow=1
    branch=$(g symbolic-ref -q --short HEAD)
    # tracked files that differ from the commit, the index not rewritten, the
    # content compared after the clean filters (git status would trust a size
    # change of a filtered file) - the same question version_info.cpp asks
    filter=
    [ "$ignore_missing" = 1 ] && filter=--diff-filter=d
    st=$(g --no-optional-locks diff --no-ext-diff --name-only --ignore-submodules=all $filter HEAD --)
    modified=0
    [ -n "$st" ] && modified=1
    if [ "$shallow" = 0 ]; then
        echo "count=$(g rev-list --count HEAD)"
    fi
    echo "hash=$hash"
    [ -n "$date" ] && echo "date=$date"
    [ -n "$branch" ] && echo "branch=$branch"
    echo "modified=$modified"
    echo "shallow=$shallow"
}

if [ -z "$header" ]; then
    info
    exit 0
fi

# C string: quotes and backslashes escaped, one \n per line
body=$(info | sed -e 's/[\\"]/\\&/g' -e 's/$/\\n/' | tr -d '\n')
tmp="$header.tmp.$$"
{
    echo "/* generated by scripts/version.sh - the version compiled in (docs/dev/version.md) */"
    printf '#define KRAKEN_BUILD_VERSION "%s"\n' "$body"   # not echo: dash's expands the \n
} > "$tmp" || exit 1
if cmp -s "$tmp" "$header"; then
    rm -f "$tmp"
else
    mv -f "$tmp" "$header"
fi
